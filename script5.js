console.log("STRING METHODS");

//LENGTH

let planet = "Jupiter";
console.log(planet.length);

let snack = "Popcorn";
console.log(snack.length);


//CHARAT

let town = "Multan";
console.log(town.charAt(3));

let instrument = "Guitar";
console.log(instrument.charAt(2));


//TO UPPERCASE

let greeting = "good afternoon";
console.log(greeting.toUpperCase());

let sport = "badminton";
console.log(sport.toUpperCase());


//TO LOWERCASE

let language = "PYTHON";
console.log(language.toLowerCase());

let color = "ORANGE";
console.log(color.toLowerCase());


//INDEXOF

let line1 = "My brother likes football";
console.log(line1.indexOf("football"));

let line2 = "The train is arriving";
console.log(line2.indexOf("train"));


//SLICE

let computer = "Laptop";
console.log(computer.slice(0, 3));

let weekday = "Saturday";
console.log(weekday.slice(3, 6));


//SUBSTRING

let dessert = "Chocolate";
console.log(dessert.substring(0, 4));

let vehicle = "Motorcycle";
console.log(vehicle.substring(5, 10));


//REPLACE

let sentence1 = "I walk to school";
console.log(sentence1.replace("walk", "drive"));

let sentence2 = "The grass is green";
console.log(sentence2.replace("green", "yellow"));


// SPLIT

let ingredients = "Rice,Chicken,Spices";
console.log(ingredients.split(","));

let letters = "A-B-C-D";
console.log(letters.split("-"));


//TRIM

let message1 = "   Have a nice day   ";
console.log(message1.trim());

let message2 = "   Welcome back   ";
console.log(message2.trim());


//INCLUDES

let sentence3 = "My favorite fruit is peach";
console.log(sentence3.includes("peach"));

let sentence4 = "The weather is sunny";
console.log(sentence4.includes("rainy"));


// CONCAT

let firstWord = "Blue";
let secondWord = "Bird";
console.log(firstWord.concat(" ", secondWord));

let firstPart = "Super";
let secondPart = "Star";
console.log(firstPart.concat(" ", secondPart));